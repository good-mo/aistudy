# 3. 从结构化用例生成 pytest 脚本的 Prompt
# ════════════════════════════════════════════════════════════

SCRIPT_GENERATION_PROMPT = '''你是资深测试工程师。根据以下【结构化测试用例】生成完整、可运行的 pytest 测试代码。

## 被测函数签名
{signatures}

## Mock 配置提示
{mocks}

## 结构化测试用例（JSON）
{structured_cases}

## 代码生成要求
1. 为每个结构化用例生成对应的测试方法，命名 `test_{{场景}}_{{期望结果}}`
2. 每个测试方法必须包含 docstring 和 Arrange/Act/Assert 三段式注释
3. 外部依赖（DB/HTTP/云SDK/文件/时间）必须使用 `@patch` 模拟
4. Mock 外部依赖时必须设置明确的 return_value
5. 代码必须严格遵循 PEP8，可运行无语法错误
6. 每个测试方法的断言应尽量反映结构化用例中的 `expected` 预期

请**只返回完整可运行的测试代码**（不含解释文字、不含 markdown 代码块围栏）。'''


def get_prompt(test_type: str) -> str:
    """
    获取指定测试类型的 Prompt 模板。

    Args:
        test_type: 测试类型 key，未知类型回退到功能测试

    Returns:
        Prompt 模板字符串
    """
    from app.generators.test_types import get_default_test_type
    return PROMPTS.get(test_type, PROMPTS[get_default_test_type()])


def get_script_generation_prompt() -> str:
    """
    获取从结构化用例生成 pytest 脚本的 Prompt 模板。
    """
    return SCRIPT_GENERATION_PROMPT
