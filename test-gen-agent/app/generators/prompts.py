"""
测试类型 Prompt 模板库
======================
按行业测试类型分类，为 LLM 提供针对性的测试生成指令。

每种类型的 Prompt 都引导 LLM 生成符合该类型特征、可运行的 pytest 测试。
同时支持「结构化用例 + 可选脚本」的生成模式（方案A）。
"""

from typing import Dict


# ════════════════════════════════════════════════════════════
# 0. 结构化用例输出模板（方案A）
# ════════════════════════════════════════════════════════════

STRUCTURED_OUTPUT_FORMAT = '''
## 输出格式（严格遵循）

请按以下 JSON 数组格式返回结构化测试用例（不要返回 markdown 代码块，只返回纯 JSON）：

```json
[
  {
    "title": "用例标题",
    "description": "用例描述",
    "test_type": "{test_type_key}",
    "preconditions": ["前置条件1", "前置条件2"],
    "test_steps": [
      {"step": "操作步骤描述", "data": "测试数据", "expected": "预期结果"}
    ],
    "test_data": {"key": "value"},
    "priority": "P0/P1/P2/P3",
    "tags": ["标签1", "标签2"],
    "risk_level": "high/medium/low",
    "execution_type": "manual/automated"
  }
]
```

**JSON 字段说明**：
- `title`: 简洁明确的用例标题
- `preconditions`: 执行前置条件（数组）
- `test_steps`: 操作步骤列表，每步含 step（操作）/ data（数据）/ expected（预期结果）
- `test_data`: 测试数据对象
- `priority`: 优先级 P0-P3
- `risk_level`: 风险等级
- `execution_type`: 执行方式 manual（手工）/ automated（自动化）
'''


# ════════════════════════════════════════════════════════════
